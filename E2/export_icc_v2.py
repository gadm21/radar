"""Export LaTeX assets for the reframed occupancy paper.

Reads E2/outputs/occupancy/{minutes_index.csv,features_*.csv,results.csv}
and writes icc_assets/{metrics.tex,balance.tex,rates.tex,boxplots.tex,
acc.tex,auc.tex,results_rows.tex}. overview.tex and layout.tex are
static TikZ and not generated here.

Run after: python E2/occupancy_pipeline.py all
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'E2'))
import common as C  # noqa: E402
import occupancy_pipeline as P  # noqa: E402

OUT = C.OUTPUT_DIR / 'occupancy'
ASSETS = ROOT / 'icc_assets'
ASSETS.mkdir(exist_ok=True)

PGF = ('\n\\begin{tikzpicture}\n\\begin{axis}[\n'
       '  width=%(w)scm, height=%(h)scm,\n'
       '  %(extra)s\n]\n')

BOXPLOT_FEATS = ['csi_amp_mean', 'csi_rv_mean', 'csi_pcv3',
                 'snr_mean', 'rd_mean', 'xy_delta']
FEAT_LBL = {
    'csi_amp_mean': 'amp. mean', 'csi_rv_mean': 'roll-var.',
    'csi_pcv3': 'PCA var.', 'snr_mean': 'SNR',
    'rd_mean': 'RD mean', 'xy_delta': 'XY delta',
}
MODEL_LBL = {
    'rf': 'RF', 'xgb': 'XGB', 'csi-cnn': 'CSI CNN',
    'csi-lstm': 'CSI LSTM', 'radar-cnn': 'Radar CNN',
    'radar-lstm': 'Radar LSTM', 'dual-cnn': 'Dual CNN',
    'dual-lstm': 'Dual LSTM',
}


def _w(name, text):
    (ASSETS / name).write_text(text)
    print('wrote', ASSETS / name)


def _boxplot_rows(x, y, style='black, fill=gray!25'):
    """pgfplots boxplot row: one prepared boxplot at position y."""
    x = np.asarray(x)[np.isfinite(x)]
    if len(x) == 0:
        return None
    q1, med, q3 = np.percentile(x, [25, 50, 75])
    iqr = q3 - q1
    lo = x[x >= q1 - 1.5 * iqr].min()
    hi = x[x <= q3 + 1.5 * iqr].max()
    return ('\\addplot+ [%s, boxplot prepared={'
            ' draw position=%.3f, lower whisker=%.4g,'
            ' lower quartile=%.4g, median=%.4g, upper quartile=%.4g,'
            ' upper whisker=%.4g, }] coordinates {};\n'
            ) % (style, y, lo, q1, med, q3, hi)


def main():
    idx = pd.read_csv(OUT / 'minutes_index.csv')
    res = pd.read_csv(OUT / 'results.csv')
    feats = {w: pd.read_csv(OUT / f'features_{w}s.csv')
             for w in P.WIN_LIST}
    f10 = feats[10]

    clean = idx[idx.usable]
    tr = clean[clean.dataset == 'train']
    te = clean[clean.dataset == 'test']
    n_tr_e, n_tr_o = int((tr.label == 0).sum()), int((tr.label == 1).sum())
    n_te_e, n_te_o = int((te.label == 0).sum()), int((te.label == 1).sum())
    n_val = int(clean.is_val.sum())
    n_fit = len(tr) - n_val
    n_aug = int(f10[(f10.dataset == 'train') & f10.aug]
                .rec_id.nunique())
    test_bal_min = min(n_te_e, n_te_o)

    # ---- metrics.tex ------------------------------------------------------
    _w('metrics.tex',
       '%% generated by E2/export_icc_v2.py\n'
       '\\newcommand{\\Nraw}{%d}\n'
       '\\newcommand{\\Ntrain}{%d}\n'
       '\\newcommand{\\NtrainFit}{%d}\n'
       '\\newcommand{\\NtrainVal}{%d}\n'
       '\\newcommand{\\Ntest}{%d}\n'
       '\\newcommand{\\NtrainEmpty}{%d}\n'
       '\\newcommand{\\NtrainOcc}{%d}\n'
       '\\newcommand{\\Naug}{%d}\n'
       '\\newcommand{\\NtestE}{%d}\n'
       '\\newcommand{\\NtestO}{%d}\n'
       '\\newcommand{\\NtestBal}{%d}\n'
       % (len(idx), len(tr), n_fit, n_val, len(te),
          n_tr_e, n_tr_o, n_aug, n_te_e, n_te_o, 2 * test_bal_min))

    # ---- balance.tex: before/after augmentation + downsampling ------------
    mx = max(n_tr_o + n_aug, n_te_o) * 1.15
    _w('balance.tex', (
        '%% before/after minute-level balancing\n'
        + PGF % {'w': 8.4, 'h': 4.6, 'extra':
                 'ybar, bar width=7pt, ymin=0, ymax=%d,\n'
                 '  symbolic x coords={train empty, train occ., test empty, test occ.},\n'
                 '  xtick=data, x tick label style={rotate=18,anchor=east,font=\\scriptsize},\n'
                 '  ylabel={minutes}, legend style={font=\\scriptsize, at={(0.02,0.97)}, anchor=north west},\n'
                 '  enlarge x limits=0.22,' % mx}
        + '\\addplot+[ybar, fill=gray!55, draw=gray] coordinates {'
          f'(train empty,{n_tr_e}) (train occ.,{n_tr_o}) '
          f'(test empty,{n_te_e}) (test occ.,{n_te_o})}};\n'
        + '\\addplot+[ybar, fill=valColor!75, draw=valColor] coordinates {'
          f'(train empty,{n_tr_e + n_aug}) (train occ.,{n_tr_o}) '
          f'(test empty,{test_bal_min}) (test occ.,{test_bal_min})}};\n'
        + '\\legend{collected, after balancing}\n'
        + '\\end{axis}\\end{tikzpicture}\n'))

    # ---- rates.tex: Hz distribution by class, colored by set --------------
    # Two panels (CSI / radar); x = class, fill shade = set x class.
    SETS = [('train', 'valColor'), ('test', 'testColor')]
    CLASSES = [(0, 'empty'), (1, 'occupied')]
    POS = {0: (1.25, 1.75), 1: (3.25, 3.75)}   # class -> (train,test) pos
    s = ('%% native sampling-rate distributions per minute\n'
         '\\begin{tikzpicture}\n\\begin{groupplot}[\n'
         '  group style={group size=2 by 1, horizontal sep=1.1cm},\n'
         '  width=4.5cm, height=4.8cm, boxplot/draw direction=y,\n'
         '  boxplot/box extend=0.38,\n'
         '  xtick={1.5,3.5}, xticklabels={empty,occ.}, xmin=0.4, xmax=4.6,\n'
         '  x tick label style={font=\\scriptsize},\n'
         '  tick label style={font=\\scriptsize}]\n')
    for pi, (mod, col, ylab) in enumerate(
            (('CSI', 'csi_hz', 'CSI packets/s'),
             ('radar', 'radar_hz', 'radar frames/s'))):
        s += f'\\nextgroupplot[ylabel={{{ylab}}}]\n'
        for ds, colr in SETS:
            for lab, _ in CLASSES:
                p = POS[lab][0 if ds == 'train' else 1]
                g = clean[(clean.dataset == ds) & (clean.label == lab)]
                shade = '!40' if lab == 0 else '!80'
                r = _boxplot_rows(g[col].values, p,
                                  f'black, fill={colr}{shade}')
                if r:
                    s += r
    s += '\\end{groupplot}\\end{tikzpicture}\n'
    _w('rates.tex', s)

    # ---- boxplots.tex: feature distributions, grouped panels --------------
    CSI_FEATS = ['csi_amp_mean', 'csi_rv_mean', 'csi_pcv3']
    RAD_FEATS = ['snr_mean', 'rd_mean', 'xy_delta']
    s = ('%% per-feature boxplots: set x class encoded by fill shade\n'
         '\\begin{tikzpicture}\n\\begin{groupplot}[\n'
         '  group style={group size=2 by 1, horizontal sep=1.1cm},\n'
         '  width=4.5cm, height=5.0cm, boxplot/draw direction=y,\n'
         '  boxplot/box extend=0.30, ymode=log,\n'
         '  xtick={2.5,8.5,14.5}, xmin=-0.2, xmax=17.2,\n'
         '  x tick label style={font=\\scriptsize},\n'
         '  tick label style={font=\\scriptsize}]\n')
    for pi, (flist, ylab) in enumerate(
            ((CSI_FEATS, 'CSI feature value'),
             (RAD_FEATS, 'radar feature value'))):
        s += (f'\\nextgroupplot[ylabel={{{ylab}}}, '
              'xticklabels={%s}]\n'
              % ','.join(FEAT_LBL[f] for f in flist))
        for j, f in enumerate(flist):
            base = j * 6 + 1
            for k, (ds, lab) in enumerate(
                    [('train', 0), ('train', 1), ('test', 0),
                     ('test', 1)]):
                g = f10[(f10.dataset == ds) & (f10.label == lab)]
                colr = 'valColor' if ds == 'train' else 'testColor'
                shade = '!40' if lab == 0 else '!80'
                r = _boxplot_rows(g[f].values, base + k,
                                  f'black, fill={colr}{shade}')
                if r:
                    s += r
    s += '\\end{groupplot}\\end{tikzpicture}\n'
    _w('boxplots.tex', s)

    # ---- acc.tex / auc.tex: bars grouped by input modality ----------------
    resm = res[res.level == 'minute'].copy()
    resw = res[res.level == 'window'].copy()

    def _grp(r):
        if r['features'] == 'dl':
            return {'csi': 0, 'radar': 1, 'dual': 2}[
                r['model'].split('-')[0]]
        return {'csi': 0, 'radar': 1, 'fusion': 2,
                'moe': 2}[r['features']]

    def _lbl(r):
        if r['features'] == 'dl':
            return r['model'].split('-')[-1].upper()
        if r['features'] in ('fusion', 'moe'):
            suf = ' cat' if r['features'] == 'fusion' else ' MoE'
            return MODEL_LBL.get(r['model'], r['model']) + suf
        return MODEL_LBL.get(r['model'], r['model'])

    def _setname(r):
        if r['features'] == 'dl':
            return {'csi': 'CSI', 'radar': 'radar',
                    'dual': 'dual'}[r['model'].split('-')[0]]
        return {'csi': 'CSI', 'radar': 'radar', 'fusion': 'concat',
                'moe': 'MoE'}[r['features']]

    MRANK = {'rf': 0, 'xgb': 1, 'cnn': 2, 'lstm': 3}
    resm['grp'] = resm.apply(_grp, axis=1)
    resm['lbl'] = resm.apply(_lbl, axis=1)
    resm['setname'] = resm.apply(_setname, axis=1)
    resm['mrank'] = resm.model.map(
        lambda m: MRANK.get(m, MRANK.get(m.split('-')[-1], 9)))

    # second level inside fusion: cat / MoE / dual
    def _sub(r):
        if r.grp != 2:
            return ''
        if r['features'] == 'dl':
            return 'dual'
        return {'fusion': 'cat', 'moe': 'MoE'}[r['features']]
    resm['sub'] = resm.apply(_sub, axis=1)
    SRANK = {'cat': 0, 'MoE': 1, 'dual': 2}

    # ordered symbolic coords: modality groups, sub-groups inside fusion,
    # gap slots between them
    combos = (resm[['model', 'features', 'grp', 'sub', 'lbl', 'mrank']]
              .drop_duplicates()
              .sort_values(
                  by=['grp', 'sub', 'mrank', 'features'],
                  key=lambda c: c.map(SRANK) if c.name == 'sub' else c)
              .reset_index(drop=True))
    coords, ticks, gaps, sgaps, grps, subs = [], [], [], [], [], []
    cmap = {}
    for _, c in combos.iterrows():
        if grps and c.grp != grps[-1]:
            gaps.append(f'gap{len(gaps)}')
            coords.append(gaps[-1])
            ticks.append('')
            grps.append(-1)
            subs.append('')
        elif subs and c.grp == 2 and c['sub'] != subs[-1]:
            sgaps.append(f'sgap{len(sgaps)}')
            coords.append(sgaps[-1])
            ticks.append('')
            grps.append(2)
            subs.append('')
        cid = f'm{len(coords)}'
        coords.append(cid)
        ticks.append(c.lbl)
        grps.append(c.grp)
        subs.append(c['sub'])
        cmap[(c.model, c.features)] = cid
    n = len(coords)
    centers, scenters = {}, {}
    for i, (g, sb) in enumerate(zip(grps, subs)):
        if g >= 0:
            centers.setdefault(g, []).append(i)
            if sb:
                scenters.setdefault(sb, []).append(i)
    hdr = [(sum(v) / len(v) / n, {0: 'CSI', 1: 'radar', 2: 'fusion'}[g])
           for g, v in sorted(centers.items())]
    shdr = [(sum(v) / len(v) / n, sb) for sb, v in scenters.items()]

    for metric, fname, ylab in (('acc', 'acc.tex', 'accuracy'),
                                ('acc_cal', 'acccal.tex',
                                 'accuracy (calibrated)'),
                                ('auc', 'auc.tex', 'ROC AUC')):
        if metric == 'acc_cal':
            # add window-level performance alongside minute-level
            series = [(w, resm) for w in P.WIN_LIST] + \
                     [(w, resw) for w in P.WIN_LIST]
            fills = ['valColor!75', 'testColor!80',
                     'valColor!30', 'testColor!30']
            legs = [f'{w}\\,s minute' for w in P.WIN_LIST] + \
                   [f'{w}\\,s window' for w in P.WIN_LIST]
            bw, lcols, lsize = '2.2pt', 4, '\\tiny'
        else:
            series = [(w, resm) for w in P.WIN_LIST]
            fills = ['valColor!75', 'testColor!80']
            legs = [f'{w}\\,s' for w in P.WIN_LIST]
            bw, lcols, lsize = '4.5pt', 2, '\\scriptsize'
        s = ('%% %s on the balanced test set\n' % metric
             + PGF % {'w': 8.6, 'h': 4.1, 'extra':
                      'ybar, bar width=%s, ymin=0, ymax=1.05,\n'
                      '  symbolic x coords={%s},\n'
                      '  xtick={%s}, xticklabels={%s},\n'
                      '  x tick label style={rotate=40,anchor=east,'
                      'font=\\tiny},\n'
                      '  ylabel={%s}, legend columns=%d,\n'
                      '  legend style={font=%s,draw=none,'
                      'fill=none, at={(0.5,-0.34)},anchor=north},\n'
                      '  clip=false, enlarge x limits=0.04,'
                      % (bw, ','.join(coords), ','.join(coords),
                        ','.join(ticks), ylab, lcols, lsize)})
        for (w, lvl), fill, leg in zip(series, fills, legs):
            s += (f'\\addplot+[ybar, fill={fill}, draw=none, '
                  'error bars/y dir=both, error bars/y explicit, '
                  'error bars/error bar style={black}] coordinates {')
            sub = (lvl[lvl.window == w]
                   .set_index(['model', 'features']))
            for (mm, ff), cid in sorted(
                    cmap.items(), key=lambda kv: int(kv[1][1:])):
                r = sub.loc[(mm, ff)]
                sd = r.get(metric + '_std', np.nan)
                sd = 0.0 if not np.isfinite(sd) else sd
                s += f'({cid},{r[metric]:.3f}) +- (0,{sd:.3f}) '
            s += f'}};\n\\addlegendentry{{{leg}}}\n'
        for g in gaps:
            s += ('\\draw[gray!55,dashed] (axis cs:%s,\\pgfkeysvalueof{'
                  '/pgfplots/ymin}) -- (axis cs:%s,\\pgfkeysvalueof{'
                  '/pgfplots/ymax});\n' % (g, g))
        for g in sgaps:
            s += ('\\draw[gray!40,dotted] (axis cs:%s,\\pgfkeysvalueof{'
                  '/pgfplots/ymin}) -- (axis cs:%s,\\pgfkeysvalueof{'
                  '/pgfplots/ymax});\n' % (g, g))
        for fx, gname in hdr:
            s += ('\\node[font=\\scriptsize\\itshape] at '
                  '(axis description cs:%.3f,1.10) {%s};\n' % (fx, gname))
        for fx, sname in shdr:
            s += ('\\node[font=\\tiny\\itshape, text=gray] at '
                  '(axis description cs:%.3f,1.04) {%s};\n' % (fx, sname))
        s += '\\end{axis}\\end{tikzpicture}\n'
        _w(fname, s)

    # ---- results_rows.tex -------------------------------------------------
    resm = resm.sort_values(['window', 'grp', 'mrank'])
    best = resm.groupby('window')['acc_cal'].transform('max')
    lines, prev = [], None
    for _, r in resm.iterrows():
        key = (int(r.window), int(r.grp))
        if prev is not None and key != prev:
            lines.append('\\midrule' if r.window != prev[0]
                         else '\\addlinespace')
        ns = int(r.get('n_seeds', 1))

        def _pm(m):
            v = r.get(m, np.nan)
            if not np.isfinite(v):
                return '--'
            sd = r.get(m + '_std', np.nan)
            if ns < 2 or not np.isfinite(sd):
                return f'{v:.3f}'
            return f'{v:.3f}\\,{{\\scriptsize$\\pm$\\,{sd:.3f}}}'

        accc = (f'\\textbf{{{r.acc_cal:.3f}}}'
                if r.acc_cal == best.loc[r.name]
                else f'{r.acc_cal:.3f}')
        if ns >= 2 and np.isfinite(r.get('acc_cal_std', np.nan)):
            accc += (f'\\,{{\\scriptsize$\\pm$\\,{r.acc_cal_std:.3f}}}')
        aucc = _pm('auc')
        kmc = _pm('acc_km')
        mlbl = (MODEL_LBL.get(r.model, r.model)
                + ({'fusion': ' cat', 'moe': ' MoE'}.get(
                    r.features, '')))
        lines.append(
            f"{int(r.window)} & {mlbl} & {r.setname} & "
            f"{_pm('acc')} & {accc} & {kmc} & {aucc} & {r.thr:.2f} \\\\")
        prev = key
    _w('results_rows.tex', '% generated results rows\n'
                           + '\n'.join(lines) + '\n\\bottomrule\n')


if __name__ == '__main__':
    main()
