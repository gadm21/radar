"""Move invalid minutes (missing radar OR CSI) into archive/<split>/.

Invalid = a minute that does NOT have both modalities valid, as recorded
in E2/outputs/modality_coverage.csv (generated by modality_coverage_plot.py
-- run that first if the CSV is stale). The minute folder is moved to
archive/<split>/<minute>; its E2 cache entry (if any) is moved to
E2/cache/archive/<split>/ so the cache stays in sync.
"""
import shutil
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
CSV = ROOT / "E2" / "outputs" / "modality_coverage.csv"
ARCHIVE = ROOT / "archive"
CACHE_ARCHIVE = ROOT / "E2" / "cache" / "archive"


def main():
    df = pd.read_csv(CSV)
    bad = df[~(df["radar_valid"] & df["csi_valid"])]
    print(f"{len(bad)} invalid minutes to archive")
    moved, missing = 0, []
    for split, grp in bad.groupby("split"):
        dst_root = ARCHIVE / split
        dst_root.mkdir(parents=True, exist_ok=True)
        cache_dst = CACHE_ARCHIVE / split
        for minute in grp["minute"]:
            src = ROOT / split / minute
            if src.exists():
                shutil.move(str(src), str(dst_root / minute))
                moved += 1
            else:
                missing.append(f"{split}/{minute}")
            npz = ROOT / "E2" / "cache" / split / f"{minute}.npz"
            if npz.exists():
                cache_dst.mkdir(parents=True, exist_ok=True)
                shutil.move(str(npz), str(cache_dst / npz.name))
        n = len(grp)
        print(f"  {split}: {n}")
    if missing:
        print("WARNING: listed as invalid but folder not found:", *missing,
              sep="\n  ")
    print(f"moved {moved} folders -> {ARCHIVE}")


if __name__ == "__main__":
    main()
