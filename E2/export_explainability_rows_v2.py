"""Export exact concise LLM replies and sensor summaries for the paper (v2)."""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "E2/outputs/frozen_v2/llm"
DEST = ROOT / "paper/icc_assets/explainability_rows.tex"
selection = pd.read_csv(SRC / "explainability_selection.csv")
mapping = pd.read_csv(SRC / "test_mapping.csv").set_index("id")
responses = {
    model: {r["id"]: r for r in json.loads((SRC / f"explainability_{model}.json").read_text())
            ["response"]["results"]}
    for model in ("gpt-4o-mini", "gpt-5.4")
}


def tex(s: str) -> str:
    s = str(s)
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"),
                 ("$", r"\$"), ("#", r"\#"), ("_", r"\_"), ("^", r"\^{}"),
                 ("~", r"\textasciitilde{}")):
        s = s.replace(a, b)
    return s


lines = ["% Generated by E2/export_explainability_rows_v2.py; reasons are verbatim."]
for rec in selection.itertuples(index=False):
    r = mapping.loc[rec.id]
    actual = "E" if rec.label == 0 else "O"
    signal = (f"CSI $A/V$: {r.csi_amp_mean:.2f}/{r.csi_rv_mean:.3f}\\newline "
              f"Radar $S$: {r.snr_mean:.2f}\\newline "
              f"$R_A/R_E/X$: {r.ra_std90:.2f}/{r.re_std90:.2f}/{r.xy_std90:.2f}")
    ref = f"{r.p_ml:.2f}/\\newline {r.p_dl:.2f}"
    answers = []
    for model in ("gpt-4o-mini", "gpt-5.4"):
        out = responses[model][rec.id]
        predicted = "E" if out["predicted_class"] == "empty" else "O"
        answers.append(f"\\textbf{{{predicted} ({out['occupied_probability']:.2f})}}. "
                       + tex(out["reason"]))
    lines.append(f"{rec.id}/{actual} & {signal} & {ref} & {answers[0]} & {answers[1]} \\\\")
    if rec.id != selection.iloc[-1].id:
        lines.append(r"\addlinespace[2pt]")
lines.append(r"\bottomrule")
DEST.write_text("\n".join(lines) + "\n")
print(DEST)
