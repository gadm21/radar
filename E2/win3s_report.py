"""Render the 3 s window experiment results into icc_assets.

Reads E2/outputs/win3s/metrics.csv + augmentation.json and writes:
  icc_assets/win3s_rows.tex    -> \\WinRowsMin / \\WinRowsWin row macros
  icc_assets/win3s_metrics.tex -> headline numbers for the prose

Model selection mirrors the paper: within each input set the classifier
with the highest validation balanced accuracy wins (AUC breaks ties);
test metrics are then reported for that frozen configuration.
"""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
import common as C  # noqa: E402

OUT = C.OUTPUT_DIR / 'win3s'
ASSETS = ROOT / 'icc_assets'

ORDER = ['csi_amp', 'csi_rollvar', 'csi_stft', 'csi_pcvar', 'csi_all',
         'snr', 'rd', 'ra', 're', 'xy', 'radar_pcvar', 'radar_all',
         'fusion']
PRETTY = {
    'csi_amp': 'CSI amp', 'csi_rollvar': 'CSI rollvar',
    'csi_stft': 'CSI STFT', 'csi_pcvar': 'CSI PCA-var',
    'csi_all': 'CSI all', 'snr': 'SNR', 'rd': 'RD', 'ra': 'RA',
    're': 'RE', 'xy': 'XY', 'radar_pcvar': 'Radar PCA-var',
    'radar_all': 'Radar all', 'fusion': 'Fusion (all)',
}
MODEL = {'rf': 'RF', 'xgb': 'XGB', 'mlp': 'MLP'}


def fmt_pct(x):
    return f'{100 * x:.1f}'


def select(df, level):
    """Validation-selected model per feature set -> joined val/test rows."""
    d = df[df.level == level]
    val = d[d.split == 'validation_minutes'].sort_values(
        ['balanced_acc', 'auc', 'model'],
        ascending=[False, False, True])
    win = val.drop_duplicates('feature_set')
    rows = []
    for _, r in win.iterrows():
        te = d[(d.feature_set == r.feature_set)
               & (d.model == r.model)
               & (d.split == 'test_minutes')]
        if len(te) != 1:
            continue
        t = te.iloc[0]
        rows.append({'feature_set': r.feature_set, 'model': r.model,
                     'val_ba': r.balanced_acc, 'val_auc': r.auc,
                     'test_ba': t.balanced_acc, 'test_auc': t.auc,
                     'tn': t.tn, 'fp': t.fp, 'fn': t.fn, 'tp': t.tp,
                     'n': t.n})
    out = pd.DataFrame(rows)
    out['order'] = out.feature_set.map({k: i for i, k in enumerate(ORDER)})
    return out.sort_values('val_ba', ascending=False)


def main():
    m = pd.read_csv(OUT / 'metrics.csv')
    aug = json.loads((OUT / 'augmentation.json').read_text())
    minute = select(m, 'minute')
    window = select(m, 'window')

    def rows(sel):
        lines = ['% auto-generated by E2/win3s_report.py']
        for _, r in sel.iterrows():
            lines.append(
                f"{PRETTY[r.feature_set]} & {MODEL[r.model]} & "
                f"{fmt_pct(r.val_ba)} & {fmt_pct(r.test_ba)} & "
                f"{r.test_auc:.3f} \\\\")
        return '\n'.join(lines)

    (ASSETS / 'win3s_rows.tex').write_text(
        '\\newcommand{\\WinRowsMin}{%\n'
        + rows(minute) + '\n}\n'
        + '\\newcommand{\\WinRowsWin}{%\n'
        + rows(window) + '\n}\n')

    best = minute.iloc[0]
    fus = minute[minute.feature_set == 'fusion'].iloc[0]
    bestw = window.iloc[0]
    metrics = {
        'WThreeMinBestInputs': PRETTY[best.feature_set],
        'WThreeMinBestModel': MODEL[best.model],
        'WThreeMinValBA': fmt_pct(best.val_ba),
        'WThreeMinTestBA': fmt_pct(best.test_ba),
        'WThreeMinTestAUC': f'{best.test_auc:.3f}',
        'WThreeMinTN': int(best.tn), 'WThreeMinFP': int(best.fp),
        'WThreeMinFN': int(best.fn), 'WThreeMinTP': int(best.tp),
        'WThreeMinN': int(best.n),
        'WThreeFusValBA': fmt_pct(fus.val_ba),
        'WThreeFusTestBA': fmt_pct(fus.test_ba),
        'WThreeFusTestAUC': f'{fus.test_auc:.3f}',
        'WThreeFusModel': MODEL[fus.model],
        'WThreeWinBestInputs': PRETTY[bestw.feature_set],
        'WThreeWinBestModel': MODEL[bestw.model],
        'WThreeWinValBA': fmt_pct(bestw.val_ba),
        'WThreeWinTestBA': fmt_pct(bestw.test_ba),
        'WThreeWinTestAUC': f'{bestw.test_auc:.3f}',
        'WThreeWinN': int(bestw.n),
        'WThreeEmptyReal': aug['empty_real'],
        'WThreeEmptyAug': aug['empty_augmented'],
        'WThreeOccupied': aug['occupied'],
    }
    lines = ['% auto-generated by E2/win3s_report.py']
    for k, v in metrics.items():
        lines.append(f'\\newcommand{{\\{k}}}{{{v}}}')
    (ASSETS / 'win3s_metrics.tex').write_text('\n'.join(lines) + '\n')
    print('wrote icc_assets/win3s_rows.tex and win3s_metrics.tex')
    print(minute[['feature_set', 'model', 'val_ba', 'test_ba', 'test_auc']]
          .to_string(index=False))


if __name__ == '__main__':
    main()
